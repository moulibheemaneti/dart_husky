import 'dart:async';
import 'dart:io';

import 'package:dart_husky/src/cli/commands/check_command.dart';
import 'package:dart_husky/src/cli/commands/install_command.dart';
import 'package:dart_husky/src/cli/commands/list_command.dart';
import 'package:dart_husky/src/config/config_model.dart';
import 'package:dart_husky/src/hooks/hook_installer.dart';
import 'package:test/test.dart';

const _config = '''
pre-commit:
  commands:
    analyze:
      run: dart analyze

commit-msg:
  commands:
    conventional:
      preset: conventional
''';

const _fix = ' - run "dart run dart_husky install" to fix';

void main() {
  late Directory project;
  late StringBuffer out;
  late StringBuffer err;

  setUp(() async {
    project = await Directory.systemTemp.createTemp('dart_husky_check_');
    out = StringBuffer();
    err = StringBuffer();
  });

  tearDown(() async {
    await project.delete(recursive: true);
  });

  int check() {
    return CheckCommand(out: out, err: err).run(projectDirectory: project);
  }

  List<String> lines(StringBuffer buffer) {
    return buffer.toString().trim().split('\n');
  }

  void writeConfig(String content) {
    File('${project.path}/dart_husky.yaml').writeAsStringSync(content);
  }

  void writeHook(HookType hookType, String content) {
    File('${project.path}/.git/hooks/${hookType.scriptName}')
        .writeAsStringSync(content);
  }

  group('CheckCommand in a git repository', () {
    setUp(() async {
      await _runGit(project.path, ['init']);
      // git creates this from its templates; make sure it exists regardless
      Directory('${project.path}/.git/hooks').createSync(recursive: true);
      writeConfig(_config);
    });

    test('exits 0 right after install', () {
      _inDirectory(project, () => InstallCommand().run());

      expect(check(), CheckCommand.exitInSync);
      expect(lines(out), ['pre-commit: in sync', 'commit-msg: in sync']);
      expect(err.toString(), isEmpty);
    });

    test('exits 0 when no hooks are configured and none are installed', () {
      writeConfig('dart_husky:\n  verbose: true\n');

      expect(check(), CheckCommand.exitInSync);
      expect(lines(out), ['No hooks configured in dart_husky.yaml']);
    });

    test('ignores sample and hand-written hooks that are not configured', () {
      writeHook(
          HookType.preCommit, HookInstaller.generateScript(HookType.preCommit));
      writeHook(
          HookType.commitMsg, HookInstaller.generateScript(HookType.commitMsg));
      writeHook(HookType.prePush, '#!/bin/sh\necho custom\n');
      File('${project.path}/.git/hooks/pre-push.sample')
          .writeAsStringSync('#!/bin/sh\n');

      expect(check(), CheckCommand.exitInSync);
      expect(lines(out), ['pre-commit: in sync', 'commit-msg: in sync']);
    });

    test('exits 1 when hooks are missing', () {
      expect(check(), CheckCommand.exitOutOfSync);
      expect(lines(out), [
        'pre-commit: missing (configured but not installed)$_fix',
        'commit-msg: missing (configured but not installed)$_fix',
      ]);
      expect(err.toString(), isEmpty);
    });

    test('exits 1 when a hook is foreign', () {
      writeHook(HookType.preCommit, '#!/bin/sh\necho custom\n');
      writeHook(
          HookType.commitMsg, HookInstaller.generateScript(HookType.commitMsg));

      expect(check(), CheckCommand.exitOutOfSync);
      expect(lines(out), [
        'pre-commit: foreign (not generated by dart_husky)'
            ' - run "dart run dart_husky install" to replace it',
        'commit-msg: in sync',
      ]);
    });

    test('exits 1 when a hook is outdated', () {
      writeHook(
          HookType.preCommit, HookInstaller.generateScript(HookType.preCommit));
      writeHook(
        HookType.commitMsg,
        '#!/bin/sh\n${HookInstaller.generatedMarker}\ndart run dart_husky run commit-msg\n',
      );

      expect(check(), CheckCommand.exitOutOfSync);
      expect(lines(out), [
        'pre-commit: in sync',
        'commit-msg: outdated (differs from what install would write)$_fix',
      ]);
    });

    test('exits 1 when an unconfigured hook is stale', () {
      _inDirectory(project, () => InstallCommand().run());
      writeHook(
          HookType.prePush, HookInstaller.generateScript(HookType.prePush));

      expect(check(), CheckCommand.exitOutOfSync);
      expect(lines(out), [
        'pre-commit: in sync',
        'commit-msg: in sync',
        'pre-push: stale (installed but not configured in dart_husky.yaml)$_fix',
      ]);
    });

    test('install fixes every out-of-sync hook it reports', () {
      writeHook(HookType.preCommit, '#!/bin/sh\necho custom\n');
      writeHook(
          HookType.prePush, HookInstaller.generateScript(HookType.prePush));
      expect(check(), CheckCommand.exitOutOfSync);

      _inDirectory(project, () => InstallCommand().run());
      out.clear();

      expect(check(), CheckCommand.exitInSync);
      expect(lines(out), ['pre-commit: in sync', 'commit-msg: in sync']);
    });

    test('exits 2 when dart_husky.yaml is missing', () {
      File('${project.path}/dart_husky.yaml').deleteSync();

      expect(check(), CheckCommand.exitCannotCheck);
      expect(out.toString(), isEmpty);
      expect(lines(err), [
        'dart_husky check: dart_husky.yaml not found. '
            'Create one in your project root.',
      ]);
    });

    test('exits 2 when dart_husky.yaml is not valid YAML', () {
      writeConfig('pre-commit:\n  commands: [unclosed\n');

      expect(check(), CheckCommand.exitCannotCheck);
      expect(out.toString(), isEmpty);
      expect(lines(err), hasLength(1));
      expect(
        lines(err).single,
        startsWith('dart_husky check: dart_husky.yaml is not valid YAML'),
      );
    });

    test('exits 2 when dart_husky.yaml is not a map', () {
      writeConfig('just a string\n');

      expect(check(), CheckCommand.exitCannotCheck);
      expect(lines(err), [
        'dart_husky check: invalid dart_husky.yaml: '
            'dart_husky.yaml must be a map of hook names to hook settings.',
      ]);
    });

    test('exits 2 when a hook has a value of the wrong type', () {
      writeConfig('pre-commit: true\n');

      expect(check(), CheckCommand.exitCannotCheck);
      expect(lines(err), hasLength(1));
      expect(
        lines(err).single,
        startsWith('dart_husky check: invalid dart_husky.yaml: '),
      );
    });

    test('exits 2 when a command is invalid', () {
      writeConfig('pre-commit:\n  commands:\n    test:\n      glob: "*"\n');

      expect(check(), CheckCommand.exitCannotCheck);
      expect(lines(err), [
        'dart_husky check: invalid dart_husky.yaml: '
            'Command must have either "run" or "preset" field.',
      ]);
    });
  });

  group('CheckCommand outside a git repository', () {
    test('exits 2 when there is no .git/hooks folder', () {
      writeConfig(_config);

      expect(check(), CheckCommand.exitCannotCheck);
      expect(out.toString(), isEmpty);
      expect(lines(err), [
        'dart_husky check: No .git/hooks directory found. '
            'Are you in a git repository?',
      ]);
    });
  });

  group('ListCommand install status', () {
    setUp(() async {
      await _runGit(project.path, ['init']);
      Directory('${project.path}/.git/hooks').createSync(recursive: true);
      writeConfig(_config);
    });

    List<String> statusLines() {
      final printed = <String>[];
      runZoned(
        () => ListCommand().run(projectDirectory: project),
        zoneSpecification: ZoneSpecification(
          print: (self, parent, zone, line) => printed.add(line),
        ),
      );
      return printed.where((line) => line.contains('command(s)')).toList();
    }

    test('shows installed only for hooks that are in sync', () {
      writeHook(
          HookType.preCommit, HookInstaller.generateScript(HookType.preCommit));

      expect(statusLines(), [
        '  pre-commit           ✅ installed — 1 command(s)',
        '  commit-msg           ❌ not installed — 1 command(s)',
      ]);
    });

    test('does not show installed for foreign or outdated hooks', () {
      writeHook(HookType.preCommit, '#!/bin/sh\necho custom\n');
      writeHook(
        HookType.commitMsg,
        '#!/bin/sh\n${HookInstaller.generatedMarker}\n',
      );

      expect(statusLines(), [
        '  pre-commit           ⚠️  not generated by dart_husky — 1 command(s)',
        '  commit-msg           ⚠️  outdated — 1 command(s)',
      ]);
    });
  });
}

/// Runs [body] with [directory] as the current directory, the way the CLI
/// runs in a project root.
void _inDirectory(Directory directory, void Function() body) {
  IOOverrides.runZoned(
    () => runZoned(
      body,
      // install prints a line per hook; keep the test output readable
      zoneSpecification: ZoneSpecification(print: (_, __, ___, ____) {}),
    ),
    getCurrentDirectory: () => directory,
  );
}

Future<void> _runGit(String workingDirectory, List<String> arguments) async {
  final result = await Process.run(
    'git',
    arguments,
    workingDirectory: workingDirectory,
  );

  if (result.exitCode != 0) {
    throw ProcessException(
      'git',
      arguments,
      result.stderr.toString(),
      result.exitCode,
    );
  }
}
