import '../config/config_model.dart';
import 'hook_installer.dart';

/// How an installed git hook compares with what `dart_husky install` would
/// write today.
enum HookStatus {
  /// The hook file is exactly what `install` would write.
  inSync('in sync'),

  /// The hook is configured, but there is no hook file.
  missing('missing (configured but not installed)'),

  /// A hook file exists, but dart_husky did not generate it.
  foreign('foreign (not generated by dart_husky)'),

  /// dart_husky generated the hook file, but it differs from the current
  /// template, for example because an older version wrote it.
  outdated('outdated (differs from what install would write)'),

  /// dart_husky generated the hook file, but the hook is no longer
  /// configured in dart_husky.yaml.
  stale('stale (installed but not configured in dart_husky.yaml)');

  /// Plain-text description, used by `dart_husky check`.
  final String description;

  const HookStatus(this.description);

  /// Works out the status of the [hookType] hook without touching the
  /// filesystem.
  ///
  /// [contents] is the hook file's contents, or null if there is no file.
  /// [isConfigured] says whether dart_husky.yaml configures [hookType].
  ///
  /// Returns null when there is nothing for dart_husky to report: the hook
  /// is not configured and there is either no file or a file that
  /// dart_husky did not generate.
  static HookStatus? of(
    HookType hookType, {
    required String? contents,
    required bool isConfigured,
  }) {
    if (contents == null) return isConfigured ? missing : null;

    final isGenerated = contents.contains(HookInstaller.generatedMarker);

    if (!isConfigured) return isGenerated ? stale : null;
    if (!isGenerated) return foreign;

    return contents == HookInstaller.generateScript(hookType)
        ? inSync
        : outdated;
  }
}
