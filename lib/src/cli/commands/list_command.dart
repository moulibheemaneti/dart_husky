import 'dart:io';

import '../../config/config_parser.dart';
import '../../hooks/hook_installer.dart';
import '../../hooks/hook_status.dart';

class ListCommand {
  /// Lists the hooks configured for the project in [projectDirectory]
  /// (defaults to [Directory.current]).
  void run({Directory? projectDirectory}) {
    final directory = projectDirectory ?? Directory.current;
    final config = ConfigParser.parse(projectDirectory: directory);
    // Unlike check, list still works outside a git repository.
    final hooksDirectory = HookInstaller.findHooksDirectory(directory);

    if (config.hooks.isEmpty) {
      print('No hooks configured in dart_husky.yaml');
      return;
    }

    print('🪝 Configured hooks:\n');

    for (final entry in config.hooks.entries) {
      final hookType = entry.key;
      final hookConfig = entry.value;
      final status = HookInstaller.readStatus(
        hooksDirectory,
        hookType,
        isConfigured: true,
      );

      print(
        '  ${hookType.scriptName.padRight(20)} ${_label(status)} — ${hookConfig.commandCount} command(s)',
      );

      for (final cmd in hookConfig.commands.entries) {
        final desc = cmd.value.run ?? 'preset: ${cmd.value.preset}';
        print('    • ${cmd.key}: $desc');
      }

      // commit-msg commands are parsed into msgCommands, not commands
      for (final cmd in hookConfig.msgCommands.entries) {
        print('    • ${cmd.key}: ${cmd.value.description}');
      }
      print('');
    }
  }

  static String _label(HookStatus? status) {
    return switch (status) {
      HookStatus.inSync => '✅ installed',
      HookStatus.outdated => '⚠️  outdated',
      HookStatus.notExecutable => '⚠️  not executable',
      HookStatus.foreign => '⚠️  not generated by dart_husky',
      // stale and null only apply to hooks that aren't configured
      HookStatus.missing || HookStatus.stale || null => '❌ not installed',
    };
  }
}
